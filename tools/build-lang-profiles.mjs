#!/usr/bin/env node
/* Generate shared/js/lang-profiles.js from shared/json/languages/<tag>/profile.json.
 * The JSON profiles are the source of truth; the classic script keeps the runtime
 * synchronous (no build step in the browser).
 *
 * Usage: node tools/build-lang-profiles.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const R = (p) => path.join(ROOT, p);
const CHECK = process.argv.includes('--check');
const read = (p) => JSON.parse(fs.readFileSync(R(p), 'utf8'));

const index = read('shared/json/languages/index.json');
const cognates = read('shared/json/languages/cognates.json');
const profiles = index.languages.map((l) => {
  const p = read(`shared/json/languages/${l.tag}/profile.json`);
  if (p.tag !== l.tag) throw new Error(`profile ${l.tag} has tag ${p.tag}`);
  return p;
});

const js = (v) => JSON.stringify(v);
const regex = (r) => `new RegExp(${js(r.source)}, ${js(r.flags)})`;
const profileText = profiles.map((p) => {
  const tips = (p.grammarTipLabels ?? []).map(([re, label, ruleId]) =>
    `[${regex(re)}, ${js(label)}, ${ruleId == null ? 'null' : js(ruleId)}]`).join(', ');
  const sourceGender = p.sourceGender ? `{
      nounsCapitalized: ${!!p.sourceGender.nounsCapitalized},
      fixWords: ${js(p.sourceGender.fixWords ?? [])},
    }` : 'null';
  return `  ${p.tag}: {
    name: ${js(p.name)},
    grammaticalGender: ${!!p.grammaticalGender},
    sourceGender: ${sourceGender},
    voices: ${js(p.voices ?? [])},
    tts: ${js(p.tts ?? { engine: 'edge' })},
    foldPreserve: ${js(p.foldPreserve ?? '')},
    nativeChars: ${js(p.nativeChars ?? '')},
    clozeStopWords: ${js(p.clozeStopWords ?? [])},
    functionWords: ${js(p.functionWords ?? [])},
    ignoreTokens: ${js(p.ignoreTokens ?? [])},
    grammarTipLabels: [${tips}],
    frequency: ${js(p.frequency ?? {})},
  }`;
}).join(',\n');

const cognateText = Object.entries(cognates).map(([key, pairs]) =>
  `    '${key}': ${js(pairs)}`).join(',\n');

const out = `/* ============================================================
   lang-profiles.js | GENERATED by tools/build-lang-profiles.mjs
   Source: shared/json/languages/<tag>/profile.json
   Do not edit by hand. Run: node tools/build-lang-profiles.mjs

   Per-language linguistic facts used by text-utils, grammar-chip, quiz
   and the Node gates. Dual-mode: browser global + CommonJS export.
   ============================================================ */

;(function (global) {
  'use strict';

  const PROFILES = {
${profileText}
  };

  const COGNATES = {
${cognateText}
  };

  const AppLangProfiles = {
    get: function (code) { return PROFILES[code]; },
    codes: function () { return Object.keys(PROFILES); },
    foldPreserve: function (code) { const p = PROFILES[code]; return p ? (p.foldPreserve || '') : ''; },
    nativeChars: function (code) { const p = PROFILES[code]; return p ? (p.nativeChars || '') : ''; },
    sourceGender: function (code) { const p = PROFILES[code]; return p ? (p.sourceGender || null) : null; },
    clozeStopWords: function (code) { const p = PROFILES[code]; return new Set(p ? p.clozeStopWords : []); },
    functionWords: function (code) { const p = PROFILES[code]; return new Set(p ? p.functionWords : []); },
    ignoreTokens: function (code) { const p = PROFILES[code]; return new Set(p ? p.ignoreTokens : []); },
    grammarTipLabels: function (code) { const p = PROFILES[code]; return p ? p.grammarTipLabels : []; },
    cognateSuffixes: function (a, b) {
      const key = [a, b].sort().join('|');
      const table = COGNATES[key];
      if (!table) return [];
      return (a <= b) ? table : table.map(function (pair) { return [pair[1], pair[0]]; });
    },
  };

  if (typeof window !== 'undefined') window.AppLangProfiles = AppLangProfiles;
  if (typeof module !== 'undefined' && module.exports) module.exports = AppLangProfiles;

})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

const file = 'shared/js/lang-profiles.js';
if (CHECK) {
  const cur = fs.readFileSync(R(file), 'utf8');
  if (cur !== out) { console.error(`DRIFT ${file}`); process.exit(1); }
  console.log('lang-profiles.js is up to date');
} else {
  fs.writeFileSync(R(file), out);
  console.log(`lang-profiles.js generated from ${profiles.length} profiles`);
}
