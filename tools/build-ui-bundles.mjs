#!/usr/bin/env node
/* Generate one UI bundle per published locale from lang/ui.js (F4).
 *
 * lang/ui.js is still the runtime aggregate (single synchronous script). This
 * build makes the per-locale artifacts explicit so a future loader can fetch one
 * bundle, and check-ui-lang can prove every published locale is 100 % complete.
 *
 * Usage: node tools/build-ui-bundles.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const R = (p) => path.join(ROOT, p);
const CHECK = process.argv.includes('--check');
const source = fs.readFileSync(R('lang/ui.js'), 'utf8');
const index = JSON.parse(fs.readFileSync(R('shared/json/languages/index.json'), 'utf8'));
const published = index.languages.filter((l) => l.ui).map((l) => l.tag);
const drift = [];

function bundleFor(code) {
  const ctx = {
    window: {},
    document: { documentElement: {} },
    navigator: { language: 'en' },
    AppLangPair: { getActive: () => ({ source: { code } }) },
    console,
  };
  vm.runInNewContext(source, ctx, { filename: 'lang/ui.js' });
  const data = ctx.window.LangUI;
  if (!data || typeof data !== 'object' || !Object.keys(data).length) throw new Error(`empty bundle for ${code}`);
  return data;
}

const manifest = [];
for (const code of published) {
  const data = bundleFor(code);
  manifest.push({ code, keys: Object.keys(data).length });
  const text = `/* GENERATED by tools/build-ui-bundles.mjs | locale: ${code}. Do not edit. */\nwindow.LangUI = ${JSON.stringify(data, null, 2)};\ndocument.documentElement.lang = '${code}';\n`;
  const file = `lang/ui/${code}.js`;
  if (CHECK) {
    const cur = fs.existsSync(R(file)) ? fs.readFileSync(R(file), 'utf8') : null;
    if (cur !== text) drift.push(file);
  } else {
    fs.mkdirSync(R('lang/ui'), { recursive: true });
    fs.writeFileSync(R(file), text);
  }
}
const manifestText = JSON.stringify({
  schemaVersion: 1,
  generatedBy: 'tools/build-ui-bundles.mjs',
  locales: manifest,
}, null, 2) + '\n';
if (CHECK) {
  const cur = fs.existsSync(R('lang/ui/index.json')) ? fs.readFileSync(R('lang/ui/index.json'), 'utf8') : null;
  if (cur !== manifestText) drift.push('lang/ui/index.json');
} else {
  fs.mkdirSync(R('lang/ui'), { recursive: true });
  fs.writeFileSync(R('lang/ui/index.json'), manifestText);
}
if (CHECK) {
  if (drift.length) { for (const f of drift) console.error(`DRIFT ${f}`); process.exit(1); }
  console.log(`UI bundles up to date: ${published.join(', ')}`);
} else {
  console.log(`UI bundles: ${published.join(', ')}`);
}
