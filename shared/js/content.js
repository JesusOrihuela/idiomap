/* ============================================================
   content.js - resolved runtime pack loader.
   Reads json/runtime/<pair>/<topic>.json, generated by
   tools/build-runtime-packs.mjs from content + source-texts + targets.
   The browser does no content/source/target joins.
   ============================================================ */
const AppContent = (() => {
  const _BASE = (function () {
    try {
      const s = document.currentScript && document.currentScript.src;
      if (s) return s.replace(/js\/[^/]*$/, '');
    } catch (_) { /* noop */ }
    return 'shared/';
  })();

  const _cache = new Map();

  function _pair() {
    return (typeof AppLangPair !== 'undefined') ? AppLangPair.getActive() : null;
  }

  function enabled() {
    // F7: the legacy payload was retired; content is always layered. Rollback is a
    // git revert of the migration commit, not a runtime flag.
    return true;
  }

  function _json(rel) {
    const key = _BASE + rel;
    if (_cache.has(key)) return _cache.get(key);
    const p = fetch(key)
      .then((r) => { if (!r.ok) throw new Error('HTTP ' + r.status + ' ' + key); return r.json(); })
      .then((data) => { _cache.set(key, data); return data; })
      .catch((e) => { _cache.delete(key); throw e; });
    _cache.set(key, p);
    return p;
  }

  /**
   * Resolve one phrase topic for the active pair.
   * The pack is generated by tools/build-runtime-packs.mjs; it already
   * contains the source text and target forms, so the browser does no joins.
   * @param {string} topic - e.g. 'greetings'
   * @returns {Promise<{phrases: Array}>}
   */
  async function topic(topic) {
    const p = _pair();
    if (!p) throw new Error('AppContent: no active pair');
    const data = await _json(`json/runtime/${p.id}/${topic}.json`);
    if (!Array.isArray(data.phrases)) {
      throw new Error(`AppContent: ${p.id}/${topic}: invalid runtime pack`);
    }
    return { phrases: data.phrases };
  }

  return { enabled, topic };
})();
